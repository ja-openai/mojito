  @Test
  public void oldOrDelayedSamplesDoNotConsumeTokensOrCreatePhantomBursts() {
    submit(observer, 1, NOW, 4);
    Bucket before = bucket(1);
    observer.observeAt(1, NOW.minusMillis(1), 0);
    observer.observeAt(1, NOW.plusSeconds(10), AiReviewSubmissionRateObserver.MAX_DELAY_MILLIS + 1);
    assertEquals(before, bucket(1));
    assertEquals(1, count("out_of_order"), 0);
    assertEquals(1, count("delayed"), 0);
    assertEquals(0, count("excess"), 0);
  }

  @Test
  public void requestPreparationDelayIsIncludedWithoutReassigningSubmissionTime() {
    ExecutorService inline = mock(ExecutorService.class);
    doAnswer(
            invocation -> {
              invocation.getArgument(0, Runnable.class).run();
              return null;
            })
        .when(inline)
        .execute(org.mockito.ArgumentMatchers.any());
    AiReviewSubmissionRateObserver delayed =
        new AiReviewSubmissionRateObserver(
            configuration,
            mapper,
            jdbc,
            new DataSourceTransactionManager(source),
            metrics,
            Clock.fixed(NOW.plusSeconds(3), ZoneOffset.UTC),
            inline);
    observers.add(delayed);
    delayed.observe(1L, NOW, System.nanoTime() - TimeUnit.SECONDS.toNanos(3));
    assertEquals(1, count("delayed"), 0);
    assertEquals(0, jdbc.queryForObject("select count(*) from mblob", Integer.class).intValue());
    assertTrue(burstWarnings().isEmpty());
  }

  @Test
  public void compareAndSetConflictRereadsAndPreservesTheCompetingSubmission() {
    submit(observer, 1, NOW, 1);
    AtomicBoolean first = new AtomicBoolean(true);
    AtomicInteger updates = new AtomicInteger();
    DataSource competing =
        interceptWrites(
            sql -> {
              if (sql.startsWith("update mblob")) {
                updates.incrementAndGet();
                if (first.getAndSet(false)) submit(observer, 1, NOW, 1);
              }
              return false;
            });
    observer(competing, metrics).observeAt(1, NOW, 0);
    assertEquals(2, updates.get());
    assertEquals(7, bucket(1).tokens(), 0);
    assertEquals(3, count("within_allowance"), 0);
    assertEquals(0, count("contended"), 0);
  }

