  @Test
  public void blockedObserverWorkerAndFullQueueNeverRunDatabaseWorkOnCaller() throws Exception {
    CountDownLatch enteredDatabase = new CountDownLatch(1);
    CountDownLatch releaseDatabase = new CountDownLatch(1);
    CountDownLatch databaseReturned = new CountDownLatch(1);
    DataSource blocked =
        new DelegatingDataSource(source) {
          @Override
          public Connection getConnection() throws SQLException {
            enteredDatabase.countDown();
            try {
              if (!releaseDatabase.await(5, TimeUnit.SECONDS)) {
                throw new SQLException("test database wait expired");
              }
              return super.getConnection();
            } catch (InterruptedException interrupted) {
              Thread.currentThread().interrupt();
              throw new SQLException("observer stopped", interrupted);
            } finally {
              databaseReturned.countDown();
            }
          }
        };
    AiReviewSubmissionRateObserver async =
        new AiReviewSubmissionRateObserver(
            configuration,
            mapper,
            new JdbcTemplate(blocked),
            new DataSourceTransactionManager(blocked),
            metrics);
    observers.add(async);
    ExecutorService caller = Executors.newSingleThreadExecutor();
    try {
      async.observe(1L);
      assertTrue(enteredDatabase.await(2, TimeUnit.SECONDS));
      caller
          .submit(
              () -> {
                for (int i = 0; i < 300; i++) async.observe(1L);
              })
          .get(1, TimeUnit.SECONDS);
      // The request path records drops in memory; reporting them is deferred off that path.
      async.close();
      assertEquals(44, count("overloaded"), 0);
      assertEquals(1, releaseDatabase.getCount());
      assertEquals(0, jdbc.queryForObject("select count(*) from mblob", Integer.class).intValue());
    } finally {
      async.close();
      releaseDatabase.countDown();
      assertTrue(databaseReturned.await(2, TimeUnit.SECONDS));
      caller.shutdownNow();
    }
  }

  private AiReviewSubmissionRateObserver observer(DataSource dataSource, MeterRegistry registry) {
    AiReviewSubmissionRateObserver result =
        new AiReviewSubmissionRateObserver(
            configuration,
            mapper,
            new JdbcTemplate(dataSource),
            new DataSourceTransactionManager(dataSource),
            registry,
            Clock.fixed(NOW, ZoneOffset.UTC),
            mock(ExecutorService.class));
    observers.add(result);
    return result;
  }

  private static void submit(
      AiReviewSubmissionRateObserver target, long userId, Instant submittedAt, int count) {
    for (int i = 0; i < count; i++) target.observeAt(userId, submittedAt, 0);
  }

  private Bucket bucket(long userId) {
    byte[] content =
        jdbc.queryForObject(
            "select content from mblob where name = ?",
            byte[].class,
            AiReviewSubmissionRateObserver.PREFIX + userId);
    return mapper.readValueUnchecked(new String(content, StandardCharsets.UTF_8), Bucket.class);
  }

  private double count(String outcome) {
    var counter = metrics.find("AiReviewSubmission.observation").tag("outcome", outcome).counter();
    return counter == null ? 0 : counter.count();
  }

  private List<ILoggingEvent> burstWarnings() {
    return logs.list.stream()
        .filter(
            event -> event.getFormattedMessage().startsWith("AI review submission burst observed"))
        .toList();
  }

  /** A real competing write between SELECT and UPDATE exercises the CAS predicate itself. */
  private DataSource interceptWrites(WriteInterception interception) {
    return new DelegatingDataSource(source) {
      @Override
      public Connection getConnection() throws SQLException {
        Connection connection = super.getConnection();
        return (Connection)
            Proxy.newProxyInstance(
                getClass().getClassLoader(),
                new Class<?>[] {Connection.class},
                (proxy, method, arguments) -> {
                  try {
                    Object result = method.invoke(connection, arguments);
                    if (method.getName().equals("prepareStatement")) {
                      String sql = (String) arguments[0];
                      PreparedStatement statement = (PreparedStatement) result;
                      return Proxy.newProxyInstance(
                          getClass().getClassLoader(),
                          new Class<?>[] {PreparedStatement.class},
                          (statementProxy, statementMethod, statementArguments) -> {
                            if (statementMethod.getName().equals("executeUpdate")
                                && interception.skip(sql)) return 0;
                            try {
                              return statementMethod.invoke(statement, statementArguments);
                            } catch (InvocationTargetException failure) {
                              throw failure.getCause();
                            }
                          });
                    }
                    return result;
                  } catch (InvocationTargetException failure) {
                    throw failure.getCause();
                  }
                });
      }
    };
  }

  private interface WriteInterception {
    boolean skip(String sql);
  }
