  @Test
  public void continuesPastFailureAndRetriesDurablyWithAccurateCounters() {
    insert(1, "clob_storage_ws/a", bytes("a"), null);
    insert(2, "clob_storage_ws/b", bytes("b"), null);
    AtomicBoolean fail = new AtomicBoolean(true);
    when(azure.createSnapshotIfAbsent(anyString(), any(byte[].class)))
        .thenAnswer(
            call -> {
              if (((String) call.getArgument(0)).contains("/1/") && fail.getAndSet(false))
                throw new IllegalStateException("secret provider URL must not be recorded");
              return objects.putIfAbsent(
                      call.getArgument(0), ((byte[]) call.getArgument(1)).clone())
                  == null;
            });
    Run run = start(10, 100);
    service.runBatch(run.id());
    assertEquals(2, store.get(run.id()).cursorId());
    assertEquals(1, store.get(run.id()).failed());
    assertEquals("IllegalStateException", store.evidence(run.id(), 0, 10).getFirst().error());
    service.runBatch(run.id());
    assertEquals("SNAPSHOT_COMPLETE", store.get(run.id()).status());
    assertEquals(2, store.get(run.id()).verified());
    assertEquals(2, store.get(run.id()).scanned());
    assertEquals(0, store.get(run.id()).failed());
    assertEquals(2, store.evidence(run.id(), 0, 10).getFirst().attempts());
  }

  @Test
  public void exhaustedFailuresRemainVisibleAndDoNotHoldTheCursor() {
    insert(1, "clob_storage_ws/a", bytes("a"), null);
    when(azure.createSnapshotIfAbsent(anyString(), any(byte[].class)))
        .thenThrow(new IllegalStateException());
    Run run = start(10, 100);
    for (int i = 0; i < 3; i++) service.runBatch(run.id());
    assertEquals("SNAPSHOT_WITH_FAILURES", store.get(run.id()).status());
    assertEquals(1, store.get(run.id()).failed());
    assertEquals(3, store.evidence(run.id(), 0, 10).getFirst().attempts());
    assertEquals(1, store.get(run.id()).cursorId());
  }

  @Test
  public void verificationMismatchPausesAndNeverOverwritesExistingObject() {
    insert(1, "clob_storage_ws/a", bytes("a"), null);
    Run run = start(10, 100);
    String target =
        BlobMigrationService.SNAPSHOT_PREFIX
            + run.id()
            + "/1/"
            + BlobMigrationService.sha256(bytes("a"));
    objects.put(target, bytes("b"));
    service.runBatch(run.id());
    assertEquals("PAUSED", store.get(run.id()).status());
    assertEquals("VERIFICATION_FAILED", store.get(run.id()).lastError());
    assertArrayEquals(bytes("b"), objects.get(target));
    assertEquals(0, store.get(run.id()).verified());
    assertEquals(1, store.get(run.id()).failed());
  }

  @Test
  public void concurrentSourceMutationIsPreservedAndNotVerifiedAsCurrent() {
    insert(1, "clob_storage_ws/a", bytes("old"), null);
    when(azure.createSnapshotIfAbsent(anyString(), any(byte[].class)))
        .thenAnswer(
            call -> {
              objects.put(call.getArgument(0), ((byte[]) call.getArgument(1)).clone());
              jdbc.update("update mblob set content = ? where id = 1", bytes("new"));
              return true;
            });
    Run run = start(10, 100);
    service.runBatch(run.id());
    var evidence = store.evidence(run.id(), 0, 10).getFirst();
    assertEquals("SOURCE_CHANGED", evidence.disposition());
    assertNotNull(evidence.verifiedAt());
    assertArrayEquals(bytes("old"), objects.get(evidence.snapshotName()));
    assertArrayEquals(
        bytes("new"), jdbc.queryForObject("select content from mblob where id = 1", byte[].class));
    assertEquals(0, store.get(run.id()).verified());
  }

