  @Test
  public void manualResumeTargetsSelectedRunAndStillHonorsPause() throws Exception {
    insert(1, "clob_storage_ws/first", new byte[] {1}, null);
    insert(2, "clob_storage_ws/second", new byte[] {2}, null);
    Run first = start(1, 1000);
    Run second = start(1, 1000);
    String ordinarilySelected = store.ready().getFirst();
    String selected = ordinarilySelected.equals(first.id()) ? second.id() : first.id();
    service.resume(selected);
    ArgumentCaptor<JobDataMap> data = ArgumentCaptor.forClass(JobDataMap.class);
    verify(scheduler)
        .triggerJob(eq(JobKey.jobKey(BlobMigrationJobConfiguration.JOB_NAME)), data.capture());
    assertEquals(selected, data.getValue().getString(BlobMigrationJob.MANUAL_RUN_ID));
    BlobMigrationJob manual = job(false);
    manual.execute(context(data.getValue()));
    assertEquals(1, store.get(selected).cursorId());
    assertEquals(0, store.get(ordinarilySelected).cursorId());
    assertEquals(1, objects.size());
    service.pause(selected);
    manual.execute(context(data.getValue()));
    assertEquals(1, store.get(selected).cursorId());
    assertEquals(0, store.get(ordinarilySelected).cursorId());
    assertEquals(1, objects.size());
  }

