  @Test
  public void pauseFencesInFlightWorkerAndRetryVerifiesExistingSnapshot() {
    insert(1, "clob_storage_ws/a", bytes("a"), null);
    Run run = start(10, 100);
    AtomicBoolean pause = new AtomicBoolean(true);
    when(azure.createSnapshotIfAbsent(anyString(), any(byte[].class)))
        .thenAnswer(
            call -> {
              boolean created =
                  objects.putIfAbsent(call.getArgument(0), ((byte[]) call.getArgument(1)).clone())
                      == null;
              if (pause.getAndSet(false)) store.request(run.id(), false);
              return created;
            });
    service.runBatch(run.id());
    assertEquals("PAUSED", store.get(run.id()).status());
    assertEquals(0, store.get(run.id()).cursorId());
    assertTrue(store.evidence(run.id(), 0, 10).isEmpty());
    assertEquals(1, objects.size());
    store.request(run.id(), true);
    service.runBatch(run.id());
    assertEquals(1, store.get(run.id()).verified());
    assertEquals(1, objects.size());
  }

  @Test
  public void leaseTakeoverRejectsOldWorkersAndParallelClaim() {
    Run run = start(10, 100);
    String old = store.claim(run.id(), 60);
    assertNotNull(old);
    assertNull(store.claim(run.id(), 60));
    jdbc.update(
        "update mblob_migration_run set lease_until = ? where id = ?",
        Timestamp.from(Instant.now().minusSeconds(60)),
        run.id());
    String next = store.claim(run.id(), 60);
    assertNotNull(next);
    assertNotEquals(old, next);
    assertThrows(BlobMigrationStore.LeaseLost.class, () -> store.renew(run.id(), old, 60));
    assertThrows(
        BlobMigrationStore.LeaseLost.class,
        () -> store.release(run.id(), old, "SNAPSHOT_COMPLETE", null));
    assertEquals(next, store.get(run.id()).leaseToken());
  }

