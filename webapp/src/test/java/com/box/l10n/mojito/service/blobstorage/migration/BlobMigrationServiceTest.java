  private BlobMigrationJob job(boolean recurring) {
    BlobMigrationJob job = new BlobMigrationJob();
    job.service = service;
    job.properties = properties;
    job.schedulingEnabled = recurring;
    return job;
  }

  private JobExecutionContext context(JobDataMap data) {
    Trigger trigger = mock(Trigger.class);
    when(trigger.getJobDataMap()).thenReturn(data);
    JobExecutionContext context = mock(JobExecutionContext.class);
    when(context.getTrigger()).thenReturn(trigger);
    return context;
  }

  @Test
  public void copiesBinaryWithoutChangingSourceOrCanonicalNamespace() {
    byte[] bytes = new byte[] {0, -1, 13, 10, 67};
    insert(1, "clob_storage_ws/example", bytes, 86400L);
    Run run = start(10, 1000);
    service.runBatch(run.id());
    var evidence = store.evidence(run.id(), 0, 10).getFirst();
    assertEquals("VERIFIED_SNAPSHOT", evidence.disposition());
    assertEquals(BlobMigrationService.sha256(bytes), evidence.digest());
    assertEquals(Long.valueOf(86400), evidence.expireSeconds());
    assertNotNull(evidence.createdDate());
    assertNotNull(evidence.verifiedAt());
    assertTrue(evidence.snapshotName().startsWith("mblob_migration/v1/" + run.id() + "/1/"));
    assertArrayEquals(bytes, objects.get(evidence.snapshotName()));
    assertArrayEquals(
        bytes, jdbc.queryForObject("select content from mblob where id = 1", byte[].class));
    assertFalse(objects.containsKey("clob_storage_ws/example"));
    Run complete = store.get(run.id());
    assertEquals("SNAPSHOT_COMPLETE", complete.status());
    assertEquals(1, complete.verified());
    assertEquals(bytes.length, complete.verifiedBytes());
    assertThrows(IllegalArgumentException.class, () -> store.request(run.id(), true));
  }

