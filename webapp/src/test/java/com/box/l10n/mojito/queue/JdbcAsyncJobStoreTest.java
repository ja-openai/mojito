  private void assertScheduledRetentionUsesDatabaseClock(Duration clockOffset) {
    // Keep seconds at zero: LocalDateTime.toString() omits them, unlike an SQL timestamp literal.
    Instant databaseNow = Instant.now().truncatedTo(ChronoUnit.MINUTES).plus(clockOffset);
    JdbcAsyncJobStore store =
        new JdbcAsyncJobStore(
            new NamedParameterJdbcTemplate(jdbcTemplate),
            AsyncJobQueueJdbcDialect.HSQL,
            "VALUES TIMESTAMP '"
                + LocalDateTime.ofInstant(databaseNow, ZoneOffset.UTC)
                    .format(DateTimeFormatter.ofPattern("uuuu-MM-dd HH:mm:ss"))
                + "'");
    AsyncJobId fresh = store.enqueueNow("assetlocalize", "fresh");
    AsyncJobId expired = store.enqueueNow("assetlocalize", "expired");
    List<AsyncJobRecord> claimed =
        store.claimNextJobs("assetlocalize", 2, "worker", Duration.ofMinutes(1));
    for (AsyncJobRecord job : claimed) {
      assertThat(store.markDone("assetlocalize", job.id(), "worker", job.leaseToken(), null))
          .isTrue();
    }
    jdbcTemplate.update(
        "UPDATE async_job_queue SET updated_date = ? WHERE id = ?",
        LocalDateTime.ofInstant(databaseNow.minus(Duration.ofDays(2)), ZoneOffset.UTC),
        Long.parseLong(expired.value()));
    AsyncJobRecord freshBefore = store.getByIds(List.of(fresh)).get(0);
    AsyncJobQueueProperties properties = new AsyncJobQueueProperties();
    properties.getQueues().put("assetlocalize", new AsyncJobQueueProperties.QueueSettings());
    properties.getRetention().setDoneRetentionMs(Duration.ofDays(1).toMillis());
    SimpleMeterRegistry registry = new SimpleMeterRegistry();
    try {
      new AsyncJobQueueRetentionCleaner(store, properties, List.of(), registry)
          .cleanupTerminalJobs();
      assertThat(store.getByIds(List.of(fresh, expired))).containsExactly(freshBefore);
    } finally {
      registry.close();
    }
  }

  @Test
  public void relativeRetentionUsesStrictCutoffAndBoundedTerminalQueueScope() {
    Instant databaseNow = Instant.parse("2030-01-02T00:00:00Z");
    JdbcAsyncJobStore store =
        new JdbcAsyncJobStore(
            new NamedParameterJdbcTemplate(jdbcTemplate),
            AsyncJobQueueJdbcDialect.HSQL,
            "VALUES TIMESTAMP '2030-01-02 00:00:00'");
    for (AsyncJobStatus status : List.of(AsyncJobStatus.DONE, AsyncJobStatus.FAILED)) {
      List<AsyncJobId> ids = new ArrayList<>();
      for (int i = 0; i < 5; i++) {
        ids.add(store.enqueueNow("assetlocalize", "{}"));
      }
      for (AsyncJobRecord job :
          store.claimNextJobs("assetlocalize", 5, "worker", Duration.ofMinutes(1))) {
        assertThat(
                status == AsyncJobStatus.DONE
                    ? store.markDone("assetlocalize", job.id(), "worker", job.leaseToken(), null)
                    : store.markFailed(
                        "assetlocalize", job.id(), "worker", job.leaseToken(), null, "failed"))
            .isTrue();
      }
      Instant cutoff = databaseNow.minus(Duration.ofDays(1));
      for (int i = 0; i < 4; i++) {
        jdbcTemplate.update(
            "UPDATE async_job_queue SET updated_date = ? WHERE id = ?",
            LocalDateTime.ofInstant(cutoff.plusNanos((i - 2L) * 1_000), ZoneOffset.UTC),
            Long.parseLong(ids.get(i).value()));
      }
      List<AsyncJobRecord> retained = store.getByIds(ids.subList(2, 5));
      assertThat(store.deleteTerminalJobsOlderThan("other", status, Duration.ofDays(1), 100))
          .isZero();
      assertThat(store.deleteTerminalJobsOlderThan("assetlocalize", status, Duration.ofDays(1), 1))
          .isEqualTo(1);
      assertThat(store.getByIds(ids)).hasSize(4);
      assertThat(store.getByIds(List.of(ids.get(0)))).isEmpty();
      assertThat(
              store.deleteTerminalJobsOlderThan("assetlocalize", status, Duration.ofDays(1), 100))
          .isEqualTo(1);
      assertThat(store.getByIds(ids)).containsExactlyElementsOf(retained);
    }
  }

  @Test
  public void scheduledRetentionKeepsCommittedBatchesWhenDeletionCountersConflict() {
    DataSource dataSource = jdbcTemplate.getDataSource();
    JdbcAsyncJobStore store =
        new JdbcAsyncJobStore(
            new NamedParameterJdbcTemplate(dataSource),
            AsyncJobQueueJdbcDialect.HSQL,
            new DataSourceTransactionManager(dataSource));
    AsyncJobQueueProperties properties = new AsyncJobQueueProperties();
    properties.getRetention().setBatchSize(1);
    List<AsyncJobId> firstBatch = new ArrayList<>();
    List<AsyncJobId> secondBatch = new ArrayList<>();
    List<AsyncJobId> protectedIds = new ArrayList<>();
    SimpleMeterRegistry registry = new SimpleMeterRegistry();
    try {
      for (String queue : List.of("assetlocalize", "later")) {
        properties.getQueues().put(queue, new AsyncJobQueueProperties.QueueSettings());
        for (AsyncJobStatus status : List.of(AsyncJobStatus.DONE, AsyncJobStatus.FAILED)) {
          firstBatch.add(retentionRow(store, queue, status, true));
          secondBatch.add(retentionRow(store, queue, status, true));
          protectedIds.add(retentionRow(store, queue, status, false));
          registry.gauge(
              "asyncJobQueue.retention.deleted",
              Tags.of("queueName", queue, "status", status.getDatabaseValue()),
              1);
        }
        AsyncJobId running = store.enqueueNow(queue, "running");
        assertThat(store.claimNextJobs(queue, 1, "worker", Duration.ofMinutes(1)))
            .extracting(AsyncJobRecord::id)
            .containsExactly(running);
        protectedIds.add(running);
        protectedIds.add(store.enqueueNow(queue, "queued"));
      }
      List<AsyncJobRecord> protectedRows = store.getByIds(protectedIds);
      List<AsyncJobRecord> nextRows = store.getByIds(secondBatch);
      var cleaner = new AsyncJobQueueRetentionCleaner(store, properties, List.of(), registry);

      cleaner.cleanupTerminalJobs();

      assertThat(store.getByIds(firstBatch)).isEmpty();
      assertThat(store.getByIds(secondBatch)).containsExactlyElementsOf(nextRows);
      assertThat(store.getByIds(protectedIds)).containsExactlyElementsOf(protectedRows);
      assertThat(registry.find("asyncJobQueue.retention.failed").meters()).isEmpty();
      assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isFalse();
      assertThat(TransactionSynchronizationManager.getResourceMap()).isEmpty();

      cleaner.cleanupTerminalJobs();

      assertThat(store.getByIds(secondBatch)).isEmpty();
      assertThat(store.getByIds(protectedIds)).containsExactlyElementsOf(protectedRows);
      assertThat(registry.find("asyncJobQueue.retention.failed").meters()).isEmpty();
    } finally {
      registry.close();
    }
  }

  private AsyncJobId retentionRow(
      JdbcAsyncJobStore store, String queue, AsyncJobStatus status, boolean old) {
    AsyncJobId id = store.enqueueNow(queue, "retained payload");
    AsyncJobRecord claimed =
        store.claimNextJobs(queue, 1, "worker", Duration.ofMinutes(1)).getFirst();
    assertThat(claimed.id()).isEqualTo(id);
    assertThat(
            status == AsyncJobStatus.DONE
                ? store.markDone(queue, id, "worker", claimed.leaseToken(), null)
                : store.markFailed(queue, id, "worker", claimed.leaseToken(), null, "failure"))
        .isTrue();
    if (old) {
      jdbcTemplate.update(
          "UPDATE async_job_queue SET updated_date = TIMESTAMP '2000-01-01 00:00:00' WHERE id = ?",
          Long.parseLong(id.value()));
    }
    return id;
  }

  @Test
  public void retentionDoesNotRepeatCommittedDeleteAfterLostAcknowledgementAndFailedDiagnostics() {
    AsyncJobId first = completedRetentionCandidate();
    AsyncJobId second = completedRetentionCandidate();
    AsyncJobRecord secondBefore = jdbcAsyncJobStore.getByIds(List.of(second)).getFirst();
    DataSource dataSource = jdbcTemplate.getDataSource();
    JdbcAsyncJobStore committed =
        new JdbcAsyncJobStore(
            new NamedParameterJdbcTemplate(dataSource),
            AsyncJobQueueJdbcDialect.HSQL,
            new DataSourceTransactionManager(dataSource));
    AsyncJobStore uncertain = mock(AsyncJobStore.class, delegatesTo(committed));
    doAnswer(
            invocation -> {
              assertThat(
                      committed.deleteTerminalJobsOlderThan(
                          "assetlocalize", AsyncJobStatus.DONE, Duration.ofDays(7), 1))
                  .isEqualTo(1);
              assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isFalse();
              throw new IllegalStateException("acknowledgement lost after committed DELETE");
            })
        .when(uncertain)
        .deleteTerminalJobsOlderThan("assetlocalize", AsyncJobStatus.DONE, Duration.ofDays(7), 1);
    var properties = new AsyncJobQueueProperties();
    properties.getQueues().put("assetlocalize", new AsyncJobQueueProperties.QueueSettings());
    properties.getRetention().setBatchSize(1);
    var registry = new SimpleMeterRegistry();
    try {
      registry.gauge(
          "asyncJobQueue.retention.failed",
          Tags.of("queueName", "assetlocalize", "status", "done"),
          1);

      new AsyncJobQueueRetentionCleaner(uncertain, properties, List.of(), registry)
          .cleanupTerminalJobs();

      assertThat(committed.getByIds(List.of(first))).isEmpty();
      assertThat(committed.getByIds(List.of(second))).containsExactly(secondBefore);
      verify(uncertain)
          .deleteTerminalJobsOlderThan("assetlocalize", AsyncJobStatus.DONE, Duration.ofDays(7), 1);
      verify(uncertain)
          .deleteTerminalJobsOlderThan(
              "assetlocalize", AsyncJobStatus.FAILED, Duration.ofDays(30), 1);
      verifyNoMoreInteractions(uncertain);
      assertThat(registry.find("asyncJobQueue.retention.deleted").meters()).isEmpty();
      assertThat(TransactionSynchronizationManager.getResourceMap()).isEmpty();
    } finally {
      registry.close();
    }
  }

