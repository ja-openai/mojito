  @Test
  public void relativeRetentionClockAndDeleteShareTransactionAndRollbackTogether() {
    AsyncJobId id = completedRetentionCandidate();
    AsyncJobRecord before = jdbcAsyncJobStore.getByIds(List.of(id)).get(0);
    DataSource dataSource = jdbcTemplate.getDataSource();
    List<Object> connectionHolders = new ArrayList<>();
    NamedParameterJdbcTemplate observingJdbc =
        new NamedParameterJdbcTemplate(dataSource) {
          @Override
          public <T> T queryForObject(String sql, SqlParameterSource params, RowMapper<T> mapper) {
            assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isTrue();
            connectionHolders.add(TransactionSynchronizationManager.getResource(dataSource));
            return super.queryForObject(sql, params, mapper);
          }

          @Override
          public int update(String sql, SqlParameterSource params) {
            assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isTrue();
            assertThat(TransactionSynchronizationManager.getCurrentTransactionIsolationLevel())
                .isEqualTo(JdbcAsyncJobStore.TRANSACTION_ISOLATION_LEVEL);
            connectionHolders.add(TransactionSynchronizationManager.getResource(dataSource));
            assertThat(super.update(sql, params)).isEqualTo(1);
            throw new IllegalStateException("failure after DELETE before commit");
          }
        };
    JdbcAsyncJobStore store =
        new JdbcAsyncJobStore(
            observingJdbc,
            AsyncJobQueueJdbcDialect.HSQL,
            new DataSourceTransactionManager(dataSource));
    assertThrows(
        IllegalStateException.class,
        () ->
            store.deleteTerminalJobsOlderThan(
                "assetlocalize", AsyncJobStatus.DONE, Duration.ofDays(1), 100));
    assertThat(connectionHolders).hasSize(2).doesNotContainNull();
    assertThat(connectionHolders.get(0)).isSameAs(connectionHolders.get(1));
    assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isFalse();
    assertThat(jdbcAsyncJobStore.getByIds(List.of(id))).containsExactly(before);
  }

