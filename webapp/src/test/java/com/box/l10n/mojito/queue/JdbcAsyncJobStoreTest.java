  private void assertInspectionReplaySurvivesTelemetryFailure(boolean localWakeupFails) {
    String queueName = "assetlocalize";
    String replacement = "{\"step\":\"operator-fixed\"}";
    String retainedError = "original terminal failure";
    DataSource dataSource = jdbcTemplate.getDataSource();
    AtomicInteger updates = new AtomicInteger();
    NamedParameterJdbcTemplate observingJdbc =
        new NamedParameterJdbcTemplate(dataSource) {
          @Override
          public int update(String sql, SqlParameterSource params) {
            assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isTrue();
            updates.incrementAndGet();
            return super.update(sql, params);
          }
        };
    JdbcAsyncJobStore store =
        new JdbcAsyncJobStore(
            observingJdbc,
            AsyncJobQueueJdbcDialect.HSQL,
            new DataSourceTransactionManager(dataSource));
    AsyncJobId id = store.enqueueNow(queueName, "{\"step\":\"original\"}");
    AsyncJobRecord originalClaim =
        store.claimNextJobs(queueName, 1, "worker-a", Duration.ofMinutes(1)).get(0);
    assertThat(originalClaim.attemptCount()).isEqualTo(1);
    assertThat(
            store.markFailed(
                queueName, id, "worker-a", originalClaim.leaseToken(), null, retainedError))
        .isTrue();
    AsyncJobRecord failed = store.getByIds(List.of(id)).get(0);
    assertThat(failed.status()).isEqualTo(AsyncJobStatus.FAILED);
    updates.set(0);

    AsyncJobQueueCoordinator coordinator = mock(AsyncJobQueueCoordinator.class);
    AsyncJobQueueWakeupNotifier notifier = mock(AsyncJobQueueWakeupNotifier.class);
    AtomicBoolean wakeupInTransaction = new AtomicBoolean();
    AtomicReference<AsyncJobRecord> committedAtWakeup = new AtomicReference<>();
    doAnswer(
            invocation -> {
              wakeupInTransaction.set(
                  TransactionSynchronizationManager.isActualTransactionActive());
              // This independent read proves replay committed before wakeups and telemetry.
              committedAtWakeup.set(jdbcAsyncJobStore.getByIds(List.of(id)).get(0));
              if (localWakeupFails) {
                throw new IllegalStateException("local wakeup unavailable");
              }
              return null;
            })
        .when(coordinator)
        .triggerPollNow(queueName);
    SimpleMeterRegistry registry = new SimpleMeterRegistry();
    try {
      registry.gauge(
          "asyncJobQueue.inspection.requeue",
          Tags.of("queueName", queueName, "result", "succeeded"),
          1);
      if (localWakeupFails) {
        registry.gauge(
            "asyncJobQueue.inspection.requeueWakeup.failed", Tags.of("queueName", queueName), 1);
      }
      AsyncJobQueueInspectionService.AsyncJobDetails result =
          new AsyncJobQueueInspectionService(store, coordinator, notifier, registry)
              .requeueFailedJob(queueName, id.value(), replacement);

      assertThat(result.id()).isEqualTo(id.value());
      assertThat(result.queueName()).isEqualTo(queueName);
      assertThat(result.status()).isEqualTo("queued");
      assertThat(result.jobData()).isEqualTo(replacement);
      assertThat(result.attemptCount()).isZero();
      assertThat(result.lastError()).isEqualTo(retainedError);
      assertThat(result.workerId()).isNull();
      assertThat(result.leaseUntil()).isNull();
      AsyncJobRecord replayed = jdbcAsyncJobStore.getByIds(List.of(id)).get(0);
      assertThat(replayed.status()).isEqualTo(AsyncJobStatus.QUEUED);
      assertThat(replayed.jobData()).isEqualTo(replacement);
      assertThat(replayed.attemptCount()).isZero();
      assertThat(replayed.lastError()).isEqualTo(retainedError);
      assertThat(replayed.createdDate()).isEqualTo(failed.createdDate());
      assertThat(replayed.availableAt()).isEqualTo(result.availableAt());
      assertThat(replayed.updatedDate()).isEqualTo(result.updatedDate());
      assertThat(replayed.workerId()).isNull();
      assertThat(replayed.leaseToken()).isNull();
      assertThat(replayed.leaseUntil()).isNull();
      assertThat(wakeupInTransaction.get()).isFalse();
      assertThat(committedAtWakeup.get()).isEqualTo(replayed);
      assertThat(updates.get()).isEqualTo(1);
      var wakeupOrder = inOrder(coordinator, notifier);
      wakeupOrder.verify(coordinator).triggerPollNow(queueName);
      wakeupOrder.verify(notifier).notifyJobAvailable(queueName, id);
      verifyNoMoreInteractions(coordinator, notifier);
      assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isFalse();
      assertThat(TransactionSynchronizationManager.hasResource(dataSource)).isFalse();

      List<AsyncJobRecord> replayClaims =
          store.claimNextJobs(queueName, 2, "worker-b", Duration.ofMinutes(1));
      assertThat(replayClaims).hasSize(1);
      AsyncJobRecord replayClaim = replayClaims.get(0);
      assertThat(replayClaim.id()).isEqualTo(id);
      assertThat(replayClaim.status()).isEqualTo(AsyncJobStatus.RUNNING);
      assertThat(replayClaim.attemptCount()).isEqualTo(1);
      assertThat(replayClaim.jobData()).isEqualTo(replacement);
      assertThat(replayClaim.lastError()).isEqualTo(retainedError);
      assertThat(replayClaim.leaseToken()).isNotEqualTo(originalClaim.leaseToken());
      assertThat(store.claimNextJobs(queueName, 1, "worker-c", Duration.ofMinutes(1))).isEmpty();
    } finally {
      registry.close();
    }
  }

