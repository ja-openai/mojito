  @Test
  public void pauseFencesStaleWorkerAfterCreateAndResumeVerifiesExistingCopy() {
    insert(1, "clob_storage_ws/a", "one", null);
    String source = snapshot(10, 100);
    Run run = create(source);
    AtomicBoolean pause = new AtomicBoolean(true);
    when(azure.createCanonicalBlobForMigrationIfAbsent(
            anyString(), any(byte[].class), any(Retention.class)))
        .thenAnswer(
            call -> {
              boolean created =
                  canonical.putIfAbsent(call.getArgument(0), remote("one", "PERMANENT", "first"))
                      == null;
              if (pause.getAndSet(false)) promotions.pause(run.id());
              return created;
            });
    assertThrows(BlobMigrationStore.LeaseLost.class, () -> service.runBatch(run.id()));
    assertEquals(0, promotions.get(run.id()).promotionCursor());
    assertNull(promotions.item(run.id(), 1));
    complete(run.id());
    assertEquals(1, promotions.get(run.id()).canonicalCount());
    verify(azure, times(1))
        .createCanonicalBlobForMigrationIfAbsent(
            anyString(), any(byte[].class), any(Retention.class));
  }

