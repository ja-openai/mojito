  @Test
  public void defaultDisabledAndSnapshotJobCannotPromote() {
    assertFalse(new BlobMigrationProperties().isPromotionEnabled());
    properties.setPromotionEnabled(false);
    assertThrows(
        IllegalStateException.class,
        () -> service.create(new BlobMigrationPromotionService.CreateRequest("x", "fence")));
    assertThrows(IllegalStateException.class, () -> service.runBatch("x"));
    insert(1, "clob_storage_ws/a", "a", null);
    snapshot(10, 100);
    verifyNoInteractions(fence);
    verify(azure, never())
        .createCanonicalBlobForMigrationIfAbsent(
            anyString(), any(byte[].class), any(Retention.class));
  }

  @Test
  public void promotesThenSeparatelyReconcilesAllRowsWithRetentionAndNoSourceDeletes() {
    insert(1, "clob_storage_ws/permanent", "one", null);
    insert(2, "clob_storage_ws/temporary", "two", 30L * 86400);
    Instant created = Instant.now().minusSeconds(10L * 86400);
    jdbc.update("update mblob set created_date = ? where id = 2", Timestamp.from(created));
    String source = snapshot(10, 100);
    Run run = create(source);
    assertEquals("READY", run.status());
    Run copied = service.runBatch(run.id());
    assertEquals("RECONCILE", copied.phase());
    assertEquals(0, copied.reconciledCount());
    assertThrows(IllegalStateException.class, () -> service.readiness(run.id()));
    Run complete = service.runBatch(run.id());
    assertEquals("RECONCILED", complete.status());
    assertEquals(2, complete.reconciledCount());
    assertEquals(1, complete.canonicalCount());
    assertEquals(1, complete.retainedCount());
    assertEquals(3, complete.retainedBytes());
    assertEquals("PERMANENT", canonical.get("clob_storage_ws/permanent").retention());
    assertFalse(canonical.containsKey("clob_storage_ws/temporary"));
    assertEquals("RETAIN_TEMPORARY_LIFETIME", promotions.item(run.id(), 2).disposition());
    assertEquals(Long.valueOf(30L * 86400), promotions.item(run.id(), 2).sourceExpireSeconds());
    assertEquals(
        snapshots.metadata(2).createdDate(), promotions.item(run.id(), 2).sourceCreatedDate());
    verify(azure, never())
        .inspectCanonicalBlobForMigration(eq("clob_storage_ws/temporary"), anyInt());
    assertArrayEquals(bytes("one"), canonical.get("clob_storage_ws/permanent").content());
    assertEquals(2, (long) jdbc.queryForObject("select count(*) from mblob", Long.class));
    assertNotNull(service.readiness(run.id()).validUntil());
    verify(fence, atLeastOnce())
        .verify(eq(source), eq("maintenance-fence"), eq(run.destinationRoot()), eq("a".repeat(64)));
  }

