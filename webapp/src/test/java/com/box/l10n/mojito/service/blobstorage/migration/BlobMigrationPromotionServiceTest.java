  @Test
  public void conflictsChangedSourcesUnknownControlsAndPreFenceDeltaRemainInReplacement() {
    insert(1, "clob_storage_ws/conflict", "one", null);
    insert(2, "clob_storage_ws/retention", "two", null);
    insert(3, "unknown/keep", "three", null);
    insert(4, "ai_review_execution/v1/capacity", "four", null);
    insert(5, "clob_storage_ws/changed", "old", null);
    String source = snapshot(10, 100);
    jdbc.update("update mblob set content = ? where id = 5", bytes("new"));
    insert(6, "clob_storage_ws/delta", "six", null);
    canonical.put("clob_storage_ws/conflict", remote("bad", "PERMANENT", "conflict"));
    canonical.put("clob_storage_ws/retention", remote("two", "MIN_1_DAY", "temporary"));
    Run run = create(source);
    complete(run.id());
    Run result = promotions.get(run.id());
    assertEquals(6, result.reconciledCount());
    assertEquals(6, result.retainedCount());
    assertEquals(0, result.canonicalCount());
    assertEquals(21, result.retainedBytes());
    assertEquals(
        List.of(
            "RETAIN_CANONICAL_CONFLICT",
            "RETAIN_RETENTION_CONFLICT",
            "RETAIN_PRESERVED_UNKNOWN",
            "RETAIN_PRESERVED_CONTROL",
            "RETAIN_SOURCE_CHANGED",
            "RETAIN_DELTA"),
        promotions.items(run.id(), 0, 10).stream()
            .map(BlobMigrationPromotionStore.Item::disposition)
            .toList());
    assertArrayEquals(bytes("bad"), canonical.get("clob_storage_ws/conflict").content());
    assertEquals(6, (long) jdbc.queryForObject("select count(*) from mblob", Long.class));
    assertTrue(promotions.hasConflicts(run.id()));
    assertThrows(IllegalStateException.class, () -> service.readiness(run.id()));
    verify(azure, never())
        .createCanonicalBlobForMigrationIfAbsent(
            anyString(), any(byte[].class), any(Retention.class));
  }

  @Test
  public void contentAndRetentionConflictsEachBlockReadinessUntilFreshPromotionResolvesThem() {
    insert(1, "clob_storage_ws/a", "one", null);
    String snapshot = snapshot(10, 100);
    for (MigrationBlob conflict :
        List.of(remote("bad", "PERMANENT", "content"), remote("one", "MIN_1_DAY", "retention"))) {
      canonical.put("clob_storage_ws/a", conflict);
      Run blocked = create(snapshot);
      complete(blocked.id());
      assertTrue(promotions.hasConflicts(blocked.id()));
      assertThrows(IllegalStateException.class, () -> service.readiness(blocked.id()));
    }
    canonical.put("clob_storage_ws/a", remote("one", "PERMANENT", "resolved"));
    Run resolved = create(snapshot);
    complete(resolved.id());
    assertFalse(promotions.hasConflicts(resolved.id()));
    assertNotNull(service.readiness(resolved.id()));
  }

