  @Test
  public void databaseLeaseClaimRejectsDuplicateWorkerAndOldTokenAfterTakeover() {
    String source = snapshot(10, 100);
    Run run = create(source);
    String old = promotions.claim(run.id(), 120);
    assertNull(promotions.claim(run.id(), 120));
    jdbc.update(
        "update mblob_migration_promotion set lease_until = ? where id = ?",
        Timestamp.from(Instant.now().minusSeconds(10)),
        run.id());
    String next = promotions.claim(run.id(), 120);
    assertNotNull(next);
    assertNotEquals(old, next);
    assertThrows(BlobMigrationStore.LeaseLost.class, () -> promotions.renew(run.id(), old, 120));
    assertThrows(
        BlobMigrationStore.LeaseLost.class,
        () -> promotions.release(run.id(), old, "RECONCILED", null, lease.validUntil()));
  }

  String snapshot(int rows, long budget) {
    var run =
        snapshotService.create(
            new BlobMigrationService.CreateRequest(
                List.of("clob_storage_ws"), rows, budget, 30, 3));
    snapshots.request(run.id(), true);
    for (int i = 0; i < 100 && !snapshots.get(run.id()).status().startsWith("SNAPSHOT_"); i++)
      snapshotService.runBatch(run.id());
    assertEquals("SNAPSHOT_COMPLETE", snapshots.get(run.id()).status());
    return run.id();
  }

  Run create(String snapshot) {
    return service.create(
        new BlobMigrationPromotionService.CreateRequest(snapshot, "maintenance-fence"));
  }

  void complete(String id) {
    for (int i = 0; i < 100 && !"RECONCILED".equals(promotions.get(id).status()); i++)
      service.runBatch(id);
    assertEquals("RECONCILED", promotions.get(id).status());
  }

  void insert(long id, String name, String content, Long expiry) {
    jdbc.update(
        "insert into mblob (id,name,content,created_date,expire_after_seconds) values (?,?,?,?,?)",
        id,
        name,
        bytes(content),
        Timestamp.from(Instant.parse("2025-01-01T00:00:00Z")),
        expiry);
  }

  static byte[] bytes(String value) {
    return value.getBytes(StandardCharsets.UTF_8);
  }

  static MigrationBlob remote(String content, String retention, String etag) {
    return new MigrationBlob(bytes(content).length, bytes(content), etag, retention);
  }
