  @Before
  @SuppressWarnings("unchecked")
  public void setup() throws Exception {
    database =
        new EmbeddedDatabaseBuilder()
            .generateUniqueName(true)
            .setType(EmbeddedDatabaseType.HSQL)
            .build();
    jdbc = new JdbcTemplate(database);
    jdbc.execute("set database sql syntax mys true");
    jdbc.execute(
        "create table mblob (id bigint generated by default as identity primary key, name varchar(255), content varbinary(1048576), created_date timestamp(6), expire_after_seconds bigint)");
    String ddl =
        new ClassPathResource("db/migration/V121__MBlob_Migration.sql")
            .getContentAsString(StandardCharsets.UTF_8)
            .replace("datetime(6)", "timestamp(6)")
            .replace(" bit ", " boolean ");
    new ResourceDatabasePopulator(new ByteArrayResource(ddl.getBytes(StandardCharsets.UTF_8)))
        .execute(database);
    var transactions = new DataSourceTransactionManager(database);
    snapshots = new BlobMigrationStore(jdbc, transactions);
    promotions = new BlobMigrationPromotionStore(jdbc, transactions, snapshots);
    properties = new BlobMigrationProperties();
    properties.setEnabled(true);
    properties.setPromotionEnabled(true);
    azure = mock(AzureBlobStorage.class);
    ObjectProvider<AzureBlobStorage> provider = mock(ObjectProvider.class);
    when(provider.getIfAvailable()).thenReturn(azure);
    when(azure.getTargetDescription(anyString()))
        .thenAnswer(
            call -> "https://example.blob.core.windows.net/container/root/" + call.getArgument(0));
    snapshotService =
        new BlobMigrationService(
            snapshots, properties, provider, mock(QuartzSchedulerManager.class));
    fence = mock(BlobMigrationMaintenanceFence.class);
    lease = mock(Lease.class);
    when(lease.manifestSha256()).thenReturn("a".repeat(64));
    when(lease.validUntil()).thenReturn(Instant.now().plusSeconds(300));
    when(fence.verify(anyString(), anyString(), anyString(), nullable(String.class)))
        .thenReturn(lease);
    service = new BlobMigrationPromotionService(snapshots, promotions, properties, fence, provider);
    backup = new HashMap<>();
    canonical = new HashMap<>();
    when(azure.createSnapshotIfAbsent(anyString(), any(byte[].class)))
        .thenAnswer(
            call ->
                backup.putIfAbsent(call.getArgument(0), ((byte[]) call.getArgument(1)).clone())
                    == null);
    when(azure.getSnapshotBytes(anyString(), anyInt()))
        .thenAnswer(
            call -> {
              assertFalse(TransactionSynchronizationManager.isActualTransactionActive());
              byte[] result = backup.get(call.getArgument(0));
              if (result == null || result.length != (int) call.getArgument(1))
                throw new AzureBlobStorage.SnapshotVerificationException();
              return result.clone();
            });
    when(azure.inspectCanonicalBlobForMigration(anyString(), anyInt()))
        .thenAnswer(
            call -> {
              assertFalse(TransactionSynchronizationManager.isActualTransactionActive());
              return Optional.ofNullable(canonical.get(call.getArgument(0)));
            });
    when(azure.createCanonicalBlobForMigrationIfAbsent(
            anyString(), any(byte[].class), any(Retention.class)))
        .thenAnswer(
            call -> {
              assertFalse(TransactionSynchronizationManager.isActualTransactionActive());
              String name = call.getArgument(0);
              byte[] bytes = ((byte[]) call.getArgument(1)).clone();
              return canonical.putIfAbsent(
                      name,
                      new MigrationBlob(
                          bytes.length, bytes, "etag-" + name, call.getArgument(2).toString()))
                  == null;
            });
  }

